"""Measure the bundled font's relative ink coverage; no runtime font download.
Requires Pillow only for regenerating the checked-in Dart table.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
font = ImageFont.truetype(str(ROOT / 'assets/fonts/JetBrainsMono-Regular.ttf'), 64)

def table(candidates):
    values = []
    for glyph in dict.fromkeys(candidates):
        canvas = Image.new('L', (64, 100), 0)
        ImageDraw.Draw(canvas).text((8, 2), glyph, font=font, fill=255)
        coverage = sum(canvas.getdata()) / 255
        values.append((glyph, coverage))
    values.sort(key=lambda item: item[1])
    maximum = values[-1][1]
    return [(glyph, coverage / maximum) for glyph, coverage in values]

out = ['// Generated by tool/calibrate_ramps.py. JetBrains Mono Regular, 64 px.',
       '// Relative antialiased ink coverage, normalized to the densest glyph.',
       '// Other fonts can change the perceived density and character widths.']
for name, candidates in [('classicCalibration', ' .:-=+*#%@'),
                         ('detailedCalibration', ''.join(chr(c) for c in range(32, 127)))]:
    out.append(f'const {name} = <(String, double)>[')
    for glyph, level in table(candidates):
        literal = json.dumps(glyph).replace('$', r'\$')
        out.append(f'  ({literal}, {level:.6f}),')
    out.append('];')
(ROOT / 'lib/features/conversion/ramp_calibration.dart').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('Calibrated classic and detailed ASCII against the bundled font.')
